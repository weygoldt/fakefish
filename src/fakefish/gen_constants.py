"""Generate the shared playback constants for BOTH languages from JSON sources.

``shared/stim_constants.json`` is the single source of truth for the fakefish
playback/session constants. This tool renders it into:

* ``firmware/eel_core/stim_levels.h`` — ``#define``\\ s the sketches consume.
* ``src/fakefish/_constants.py`` — module constants the Python toolchain consumes.

A **second, independent** source is rendered here too, into C only:

* ``data/loc_model_params.json`` (vendored) -> ``firmware/eel_core/loc_model_params.h``
  — the fitted resting-rhythm model's tables, for ``loc_rhythm.h``.

Python does not need a generated copy of that one: ``fakefish.loc_model`` reads the JSON
directly, which is precisely what makes the C the only transcription and therefore the
only thing that can drift. See :func:`render_loc_header`.

None of the generated files may be hand-edited: ``fakefish-gen-constants`` overwrites all
three, and a pytest guard (``tests/test_gen_constants.py``) fails if regenerating produces
a diff. That guard is what makes the JSON authoritative rather than merely aspirational.

**Why codegen when each group has one consumer today.** The SD-card path's levels and
timings live in Python (``build_sd_card.py`` bakes them into the WAVs) while the RC
path's live-synthesis constants live in C — two languages, two files, no shared
definition. Consolidating them here removes the drift hazard, makes the *pair* of
devices legible in one place, and means a future surface that renders SD-style sessions
live on-device already has the constants in C.

**The sample rate is deliberately NOT in the JSON.** It stays single-sourced in the
export-generated ``eel_stimuli.h`` (``STIM_SAMPLE_RATE_HZ``) and
``export_teensy_stimuli.PLAYBACK_RATE_HZ``. Every sample-unit figure below is *derived*
from it — in C by the preprocessor, in Python at import — so the rate is stated once.

**There is one marker left, and only the SD device has it** (``SD_MARKER_*`` = the card's
6-pulse alternating-polarity lead-in). The RC device's count-coded 100 Hz burst was removed
on 2026-08-22: its per-pulse log cannot be absent, so the trial was already recorded, and
for a SHAM the burst was not redundant but a stimulus inside the no-stimulus control. The
SD device keeps its own because it writes no log at all.
"""

