# ===== the vendored resting-rhythm model -> C ==========================================
#
# WHY THIS IS GENERATED AND NOT TYPED OUT. ``LOCALIZATION_GENERATIVE_SPEC.md`` §7 ships a
# ready-to-paste C listing, and pasting it would be wrong: as dropped on 2026-08-21 that
# listing disagrees with the fitted parameters it claims to implement — ``TAU[0]`` 3.200
# against a shipped ``tau_fast_s`` of 2.5, ``HAZ_B0`` −4.872 against −4.8118, and both
# mixture widths off in the third decimal. The JSON is the self-consistent one (its
# interval table was calibrated AT tau 2.5, and running the reference sampler with it
# reproduces the spec's own §6 validation column, while substituting 3.2 moves the median
# interval off the measured 317 ms). Deriving the header from the JSON makes that whole
# class of transcription error impossible instead of merely discouraged.

#: Burn-in intervals discarded at power-on. The components' stationary distribution is
#: defined in continuous time while the model is observed at its own pulse times, so a
#: cold state starts noticeably slow; the reference implementation's ``new_state`` default.
LOC_BURN_IN = 40


def load_loc_model(path: Path = LOC_MODEL_JSON) -> dict:
    """Read the vendored fitted parameters (no ``_comment`` convention here)."""
    return json.loads(path.read_text())


def _uniform_step(values: list[float], label: str) -> float:
    """Assert a grid is evenly spaced and return its step.

    Load-bearing: the C looks both tables up with O(1) index arithmetic
    (``i = (x - lo) / step``) rather than a search, which is only equivalent to the
    reference's ``np.interp`` while the grid is uniform. A re-drop that re-spaced either
    grid would otherwise index silently wrong — the model would still run, and every
    interval it produced would come from the wrong knot.
    """
    if len(values) < 2:
        raise ValueError(f"{label}: need at least two knots, got {len(values)}")
    step = (values[-1] - values[0]) / (len(values) - 1)
    for i, v in enumerate(values):
        if abs(v - (values[0] + i * step)) > 1e-9:
            raise ValueError(
                f"{label} is not evenly spaced at index {i} ({v} vs "
                f"{values[0] + i * step}) — loc_rhythm.h indexes it by arithmetic, so a "
                f"non-uniform grid must be looked up by search instead"
            )
    return step


def validate_loc_model(p: dict) -> None:
    """Fail loudly on a re-drop that breaks what the C port assumes."""
    st, mg, kn, nz = p["state"], p["marginal"], p["knobs"], p["noise"]

    # (1) The variances sum to 1 BY CONSTRUCTION — that is what makes the score standard
    #     normal and therefore makes the quantile table *be* the interval distribution.
    total = sum(st[k] for k in ("var_fast", "var_medium", "var_slow", "var_offset", "var_white"))
    if abs(total - 1.0) > 1e-6:
        raise ValueError(f"state variances sum to {total}, not 1 — the score is not standard normal")

    # (2) Both grids must be uniform (see _uniform_step) ...
    _uniform_step(mg["z_knots"], "marginal.z_knots")
    _uniform_step(kn["randomness"], "knobs.randomness")
    if kn["randomness"][0] != 0.0:
        raise ValueError("knobs.randomness must start at 0 (the metronome end of the knob)")

    # (3) ... and the interval table must be a quantile function, i.e. monotone. A
    #     non-monotone table would map a faster state to a longer interval.
    knots = mg["log_ipi_knots"]
    if any(b <= a for a, b in zip(knots[:-1], knots[1:], strict=True)):
        raise ValueError("marginal.log_ipi_knots is not strictly increasing")
    if len(knots) != len(mg["z_knots"]):
        raise ValueError("marginal.log_ipi_knots and z_knots differ in length")

    # (4) The gain table is what holds the tick tempo where the rate knob says it is, so at
    #     randomness 1.0 — the measured eel, the knob's definition point — it must be 1.
    i_one = kn["randomness"].index(1.0)
    if abs(kn["gain_median_anchor"][i_one] - 1.0) > 1e-6:
        raise ValueError(
            f"knobs.gain_median_anchor at randomness 1.0 is "
            f"{kn['gain_median_anchor'][i_one]}, not 1.0 — the rate knob would be "
            f"mis-scaled at its own reference point"
        )
    if len(kn["gain_median_anchor"]) != len(kn["randomness"]):
        raise ValueError("knobs.gain_median_anchor and knobs.randomness differ in length")

    # (5) The noise mixture is unit-variance by construction (mix_p*lo^2 + (1-p)*hi^2 == 1);
    #     if it is not, every variance in the state table is silently rescaled.
    var = nz["mix_p"] * nz["mix_sd_lo"] ** 2 + (1.0 - nz["mix_p"]) * nz["mix_sd_hi"] ** 2
    if abs(var - 1.0) > 1e-3:
        raise ValueError(f"noise mixture variance is {var}, not 1")


def render_loc_header(p: dict, rate_hz: int, eod_len: int | None = None) -> str:
    """Render ``firmware/eel_core/loc_model_params.h`` from the vendored parameters."""
    st, mg, kn, nz = p["state"], p["marginal"], p["knobs"], p["noise"]
    ref, prov = p["reference_statistics"], p["provenance"]

    z = mg["z_knots"]
    z_step = _uniform_step(z, "marginal.z_knots")
    s_step = _uniform_step(kn["randomness"], "knobs.randomness")
    taus = [st["tau_fast_s"], st["tau_medium_s"], st["tau_slow_s"]]
    sds = [st["var_fast"] ** 0.5, st["var_medium"] ** 0.5, st["var_slow"] ** 0.5]
    ipi_lo = 2.718281828459045 ** mg["log_ipi_knots"][0]
    ipi_hi = 2.718281828459045 ** mg["log_ipi_knots"][-1]

    def table(name: str, values: list[float], dim: str, per_line: int = 4) -> list[str]:
        # Sized by the count macro on purpose: the C indexes these by arithmetic derived
        # from the same macro, so a table and its count going out of step must be a
        # compile error rather than a read past the end.
        out = [f"static const float {name}[{dim}] = {{"]
        for i in range(0, len(values), per_line):
            out.append("  " + " ".join(_f(v) + "," for v in values[i:i + per_line]))
        out.append("};")
        return out

    L: list[str] = []
    a = L.append
    a(f"// {_LOC_BANNER}")
    a("//")
    a("// The FITTED resting localization rhythm of Electrophorus — the tables consumed by")
    a("// loc_rhythm.h. Fitted in eeltracker (analyses/localization_rhythm) to 29 h of")
    a(f"// single-eel stretches: {prov['n_resting_intervals']} resting intervals over "
      f"{prov['n_slices']} slices,")
    a(f"// {prov['n_recordings_used']} recordings, {prov['n_sites']} sites of {prov['dataset']}.")
    a("// Provenance and every caveat: docs/LOCALIZATION_GENERATIVE_SPEC.md.")
    a("//")
    a("// DO NOT hand-type these from the spec's §7 listing — it disagrees with the fitted")
    a("// parameters (tau_fast, the hazard intercept and both mixture widths). Edit nothing")
    a("// here: re-drop data/loc_model_params.json from eeltracker and re-run the codegen.")
    a("//")
    a("// The BURST HAZARD is deliberately absent. The model's interrupt() — the fish's own")
    a("// decision to fire a fast run — is not ported: this device only ever emits an")
    a("// operator-requested volley, so that every volley in the water carries a marker and a")
    a("// sham is true silence. See loc_rhythm.h and CLAUDE.md.")
    a("#pragma once")
    a("")
    a("// ===== state: Ornstein-Uhlenbeck components relaxing in WALL-CLOCK time ====")
    a("// Not in pulse count. After a 3 s silence the fish has forgotten more than after")
    a("// three 100 ms intervals, and refitting per-pulse costs 699 nats (spec §2.2).")
    a(f"#define LOC_N_COMPONENTS {len(taus)}")
    a("")
    a("// Time constants (s): fast, medium, slow.")
    L.extend(table("LOC_TAU_S", taus, "LOC_N_COMPONENTS", 3))
    a("// Component sds in score units (sqrt of each variance; they sum to 1 with the white")
    a("// and offset terms, which is what makes the score standard normal).")
    L.extend(table("LOC_SD", sds, "LOC_N_COMPONENTS", 3))
    a(f"#define LOC_SD_WHITE  {_f(st['var_white'] ** 0.5)}  // fresh jitter, per pulse")
    a(f"#define LOC_SD_OFFSET {_f(st['var_offset'] ** 0.5)}  // per-power-on tempo offset")
    a("")
    a("// ===== noise: PEAKED, not Gaussian =========================================")
    a("// A unit-variance two-scale Gaussian mixture. The fish holds its rate almost exactly")
    a("// and then jumps (measured excess kurtosis +1.5); Gaussian noise of the same variance")
    a("// gets the interval distribution right and still sounds wrong — median CV2 0.60")
    a(f"// against a measured {nz['measured_cv2_pooled']:.3f}. One extra uniform and a branch.")
    a(f"#define LOC_MIX_P     {_f(nz['mix_p'])}")
    a(f"#define LOC_MIX_SD_LO {_f(nz['mix_sd_lo'])}")
    a(f"#define LOC_MIX_SD_HI {_f(nz['mix_sd_hi'])}")
    a("")
    a("// ===== the interval quantile table =========================================")
    a("// score -> log(interval in seconds), linearly interpolated, CLAMPED at both ends.")
    a("// The clamp is deliberate: the bottom is the 25 ms resting/volley antimode, so the")
    a("// resting rhythm can never intrude into volley territory, and the top is the 99.98th")
    a("// percentile of the measured intervals, beyond which there is nothing to extrapolate.")
    a("//")
    a("// CALIBRATED, and the calibration is load-bearing: the model is observed at its own")
    a("// pulse times, which over-visits the fast side, so feeding the raw measured quantiles")
    a("// in would run the device 43 % fast. marginal.uncalibrated_ipi_ms_knots in the JSON is")
    a("// the raw distribution — for comparison, never as the table.")
    a(f"#define LOC_N_KNOTS   {len(z)}")
    a(f"#define LOC_Z_LO      {_f(z[0])}")
    a(f"#define LOC_Z_HI      {_f(z[-1])}")
    a(f"#define LOC_Z_STEP    {_f(z_step)}")
    a(f"#define LOC_Z_SCALE   {_f(1.0 / z_step)}  // (z - LOC_Z_LO) * this == knot index")
    L.extend(table("LOC_LOG_IPI_KNOTS", mg["log_ipi_knots"], "LOC_N_KNOTS"))
    a(f"// Table range: {1e3 * ipi_lo:.1f} ms .. {ipi_hi:.1f} s at tempo 1.")
    a(f"#define LOC_IPI_MIN_S {_f(ipi_lo)}")
    a(f"#define LOC_IPI_MAX_S {_f(ipi_hi)}")
    if eod_len is not None:
        a(f"// The fastest interval the table can produce is {1e3 * ipi_lo:.1f} ms == "
          f"{round(ipi_lo * rate_hz)} samples")
        a(f"// at tempo 1, against a {eod_len}-sample EOD, so locgen's no-overlap invariant")
        a("// holds with a wide margin until the rate knob is turned well past a real eel.")
    a("")
    a("// ===== the randomness knob's gain table ====================================")
    a("// 0 = a metronome at exactly the nominal tempo, 1 = the measured eel, useful to ~1.5.")
    a("// The knob scales the state score; this table then holds the TICK TEMPO (1 / median")
    a("// interval) where the rate knob says it is as the score's spread changes. Without it,")
    a("// randomness 0 would emit the calibrated table's own score-zero knot instead of the")
    a("// fish's median.")
    a("//")
    a("// MEDIAN ANCHOR. A heavy-tailed interval distribution cannot hold its median and its")
    a("// mean at once. This device holds the median — the tick tempo, the number quoted as an")
    a("// eel's discharge rate — so the CH3 throttle's Hz scale keeps meaning 'the fish ticks")
    a("// at this rate'. The cost is that sweeping randomness moves the dose (3.9 -> 1.1")
    a("// pulses/s across the knob). knobs.gain_mean_anchor in the JSON is the other table,")
    a("// which holds the dose instead — what the retired lognormal knob meant. Switching")
    a("// anchors means rendering that table here and re-reading spec §5.3.")
    a(f"#define LOC_KNOB_N     {len(kn['randomness'])}")
    a(f"#define LOC_KNOB_STEP  {_f(s_step)}")
    a(f"#define LOC_KNOB_SCALE {_f(1.0 / s_step)}  // randomness * this == knob index")
    a(f"#define LOC_KNOB_MAX   {_f(kn['randomness'][-1])}")
    L.extend(table("LOC_KNOB_GAIN", kn["gain_median_anchor"], "LOC_KNOB_N"))
    a("")
    a("// ===== reference points ====================================================")
    a("// The measured tick tempo: 1 / the median resting interval. This is what rate == 1")
    a("// means, and it is what converts the CH3 throttle's Hz setting into a tempo multiplier.")
    a("// NOTE the other rate number, deliberately not used here: a single eel emits about")
    a("// 1.1 pulses/s averaged over a slice. Both are right — the distribution is")
    a("// heavy-tailed. Quote this one for 'how fast does it tick'.")
    a(f"#define LOC_NOMINAL_TICK_HZ {_f(ref['resting_ipi_median_hz'])}")
    a(f"#define LOC_MEDIAN_IPI_MS   {_f(ref['resting_ipi_ms']['50'])}")
    a("// Intervals discarded at power-on to clear the cold-start transient (spec §7).")
    a(f"#define LOC_BURN_IN         {LOC_BURN_IN}")
    a("")
    return "\n".join(L)


def generate(source: Path = SOURCE_JSON) -> dict[Path, str]:
    """Render every output. Returns ``{path: content}`` without writing anything."""
    c = load_constants(source)
    eod_len = _eod_hv_len()
    validate(c, RATE_HZ, eod_len=eod_len)
    loc = load_loc_model()
    validate_loc_model(loc)
    return {
        OUT_HEADER: render_header(c),
        OUT_PYTHON: render_python(c),
        OUT_LOC_HEADER: render_loc_header(loc, RATE_HZ, eod_len=eod_len),
    }


@app.command()
def main(
    check: bool = typer.Option(
        False, "--check", help="Do not write; exit non-zero if a generated file is stale."
    ),
    verbose: int = typer.Option(0, "--verbose", "-v", count=True, help="-v INFO, -vv DEBUG."),
) -> None:
    """Regenerate ``stim_levels.h`` + ``_constants.py`` from ``shared/stim_constants.json``."""
    configure_logging(verbose)
    rendered = generate()

    stale = []
    for path, content in rendered.items():
        current = path.read_text() if path.exists() else None
        if current == content:
            log.info("up to date: %s", path)
            continue
        stale.append(path)
        if check:
            log.error("STALE: %s", path)
        else:
            path.write_text(content)
            log.info("wrote %s", path)

    if check:
        if stale:
            names = ", ".join(str(p) for p in stale)
            typer.echo(
                f"STALE (re-run fakefish-gen-constants and commit): {names}", err=True
            )
            raise typer.Exit(code=1)
        typer.echo(f"up to date: {len(rendered)} generated file(s)")
        return
    typer.echo(f"generated {len(rendered)} file(s) from {SOURCE_JSON.name}")


if __name__ == "__main__":
    app()
